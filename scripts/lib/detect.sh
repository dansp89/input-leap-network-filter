# ---------------------------------------------------------------- OS
detect_os() {
  OS_ID="unknown" OS_VERSION="" OS_NAME="Linux" OS_LIKE="" OS_FAMILY="unknown"
  local f=/etc/os-release line k v
  [[ -n ${ILNF_OS_RELEASE:-} ]] && f=$ILNF_OS_RELEASE
  if [[ -r $f ]]; then
    # Parsed, not sourced.
    while IFS= read -r line; do
      [[ $line == *=* ]] || continue
      k=${line%%=*} v=${line#*=} v=${v#\"} v=${v%\"} v=${v#\'} v=${v%\'}
      case $k in
        ID) OS_ID=$v ;;
        VERSION_ID) OS_VERSION=$v ;;
        PRETTY_NAME) OS_NAME=$v ;;
        ID_LIKE) OS_LIKE=$v ;;
      esac
    done <"$f"
  fi
  case " $OS_ID $OS_LIKE " in
    *" debian "* | *" ubuntu "*) OS_FAMILY=debian ;;
    *" fedora "* | *" rhel "* | *" centos "*) OS_FAMILY=fedora ;;
    *" arch "*) OS_FAMILY=arch ;;
    *" suse "* | *" opensuse "*) OS_FAMILY=suse ;;
  esac
  ARCH=$(uname -m)
}

# Tested = actually validated by the maintainers. Everything else is honest
# about not having been tested yet.
support_level() {
  case "$OS_ID:$OS_VERSION" in
    ubuntu:22.04) echo Tested ;;
    *)
      case $OS_FAMILY in
        debian | fedora | arch | suse) echo Experimental ;;
        *) echo Unsupported ;;
      esac
      ;;
  esac
}

detect_pkg_manager() {
  PKG_MGR=none
  local m
  for m in apt-get dnf yum pacman zypper; do
    if command -v "$m" >/dev/null 2>&1; then
      PKG_MGR=$m
      break
    fi
  done
}

has_sudo() { command -v sudo >/dev/null 2>&1; }

detect_toolchain() {
  CXX_BIN=""
  local c
  for c in "${CXX:-}" g++ clang++ c++; do
    [[ -n $c ]] && command -v "$c" >/dev/null 2>&1 && {
      CXX_BIN=$(command -v "$c")
      break
    }
  done
  CMAKE_BIN=$(command -v cmake 2>/dev/null || true)
  PKGCONFIG_BIN=$(command -v pkg-config 2>/dev/null || true)
}

# ---------------------------------------------------------------- Input Leap
# Candidate executables, in priority order. OPT_PATH overrides everything.
find_input_leap_candidates() {
  local -a c=()
  [[ -n $OPT_PATH ]] && c+=("$OPT_PATH")
  local p
  p=$(command -v input-leap 2>/dev/null || true)
  [[ -n $p ]] && c+=("$p")
  c+=("$HOME/.local/bin/input-leap" /usr/local/bin/input-leap /usr/bin/input-leap
    /opt/input-leap/bin/input-leap /opt/input-leap/input-leap)
  local x
  for x in "${c[@]}"; do [[ -e $x ]] && printf '%s\n' "$x"; done | awk '!seen[$0]++'
}

# Is FILE a wrapper generated by this project?
is_our_wrapper() { [[ -f $1 ]] && ! is_elf "$1" && grep -qF -- "$WRAPPER_MARKER" "$1" 2>/dev/null; }

# Is FILE the legacy hand-made wrapper (export LD_PRELOAD ... exec *.original)?
is_legacy_wrapper() {
  [[ -f $1 ]] && ! is_elf "$1" && [[ $(stat -c %s -- "$1") -lt 4096 ]] || return 1
  grep -q 'LD_PRELOAD=.*network-filter\.so' "$1" && grep -q 'exec .*input-leap\.original' "$1"
}

# Which package (if any) owns FILE.
package_owner() {
  local f=$1 out=""
  if command -v dpkg >/dev/null 2>&1; then
    out=$(dpkg -S -- "$f" 2>/dev/null | head -n1 | cut -d: -f1) && [[ -n $out ]] && {
      echo "dpkg:$out"
      return
    }
  fi
  if command -v rpm >/dev/null 2>&1; then
    out=$(rpm -qf -- "$f" 2>/dev/null) && [[ -n $out && $out != *"not owned"* ]] && {
      echo "rpm:$out"
      return
    }
  fi
  if command -v pacman >/dev/null 2>&1; then
    out=$(pacman -Qqo -- "$f" 2>/dev/null) && [[ -n $out ]] && {
      echo "pacman:$out"
      return
    }
  fi
  echo ""
}

# Fills IL_* variables describing the Input Leap installation.
# IL_STATE: ok | missing | unsupported
detect_input_leap() {
  IL_STATE=missing IL_LAUNCH="" IL_REAL="" IL_METHOD="" IL_QT="" IL_VERSION="" IL_REASON=""
  IL_PKG="" IL_LEGACY=0 IL_RUNPATH=""
  manifest_load || true

  local cand real
  # A managed install already knows where the real binary is.
  if [[ -n ${MF[original]:-} && -e ${MF[original]} ]]; then
    IL_LAUNCH=${MF[target]} IL_REAL=${MF[original]}
  else
    while IFS= read -r cand; do
      IL_LAUNCH=$cand
      if is_our_wrapper "$cand"; then
        real=$(sed -n "s/^ILNF_ORIGINAL='\(.*\)'$/\1/p" "$cand" | head -n1)
      elif is_legacy_wrapper "$cand"; then
        real="$cand.original"
        IL_LEGACY=1
      else
        real=$(readlink -f -- "$cand")
      fi
      IL_REAL=$real
      break
    done < <(find_input_leap_candidates)
  fi

  if [[ -z $IL_LAUNCH ]]; then
    if command -v flatpak >/dev/null 2>&1 && flatpak info io.github.input_leap.input-leap >/dev/null 2>&1; then
      IL_STATE=unsupported IL_METHOD=flatpak IL_REASON=$(t reason_flatpak)
    elif [[ -d /snap/input-leap ]]; then
      IL_STATE=unsupported IL_METHOD=snap IL_REASON=$(t reason_snap)
    fi
    return
  fi

  case $IL_LAUNCH in
    /snap/* | /var/lib/snapd/*) IL_STATE=unsupported IL_METHOD=snap IL_REASON=$(t reason_snap); return ;;
    */flatpak/*) IL_STATE=unsupported IL_METHOD=flatpak IL_REASON=$(t reason_flatpak); return ;;
  esac
  if [[ $IL_REAL == *.AppImage || $IL_REAL == *.appimage ]] || { [[ -f $IL_REAL ]] && grep -aqm1 'AppImage' <(head -c 2048 -- "$IL_REAL" 2>/dev/null); }; then
    IL_STATE=unsupported IL_METHOD=appimage IL_REASON=$(t reason_appimage)
    return
  fi
  if ! is_elf "$IL_REAL"; then
    IL_STATE=unsupported IL_METHOD=unknown IL_REASON=$(t reason_not_elf "$IL_REAL")
    return
  fi

  IL_PKG=$(package_owner "$IL_REAL")
  if [[ -n $IL_PKG ]]; then
    IL_METHOD=package
  else
    case $IL_REAL in
      "$HOME"/*) IL_METHOD=local ;;
      /usr/local/* | /opt/*) IL_METHOD=custom ;;
      *) IL_METHOD=custom ;;
    esac
  fi

  # Static analysis only (readelf), the binary is never executed.
  local dyn
  dyn=$(LC_ALL=C readelf -d -- "$IL_REAL" 2>/dev/null || true)
  if grep -q 'libQt6Network' <<<"$dyn"; then
    IL_QT=6
  elif grep -q 'libQt5Network' <<<"$dyn"; then
    IL_QT=5
  else
    IL_STATE=unsupported IL_REASON=$(t reason_no_qtnetwork)
    return
  fi
  IL_RUNPATH=$(sed -n 's/.*(R\(UN\)\{0,1\}PATH).*\[\(.*\)\]/\2/p' <<<"$dyn" | head -n1)
  local syms
  syms=$(LC_ALL=C readelf --dyn-syms -W -- "$IL_REAL" 2>/dev/null || true)
  if [[ $syms != *"$FILTER_SYMBOL"* ]]; then
    IL_STATE=unsupported IL_REASON=$(t reason_no_symbol)
    return
  fi
  IL_VERSION=$(grep -aoE '[0-9]+\.[0-9]+\.[0-9]+(-git-[0-9]{4}-[0-9]{2}-[0-9]{2}-[0-9a-f]+)?' -- "$IL_REAL" 2>/dev/null |
    grep -E '^[0-9]+\.[0-9]+\.[0-9]+-git' | head -n1 || true)
  IL_STATE=ok
}

# Install mode: "inplace" replaces the user-owned launcher with a wrapper;
# "external" never touches the binary and uses a separate wrapper + desktop
# overrides (package-managed or system-owned binaries).
choose_mode() {
  if [[ -n ${MF[mode]:-} ]]; then
    echo "${MF[mode]}"
    return
  fi
  local dir
  dir=$(dirname -- "$IL_LAUNCH")
  if [[ $IL_METHOD == local && -O $IL_LAUNCH && -w $dir && ! -L $IL_LAUNCH ]]; then
    echo inplace
  else
    echo external
  fi
}

# Running GUI processes (informational).
running_input_leap() { pgrep -u "$(id -u)" -a -f 'input-leap(\.original)?( |$)' 2>/dev/null | grep -v -e input-leaps -e input-leapc -e "$ILNF_NAME" || true; }

# Desktop entries that launch Input Leap.
find_desktop_entries() {
  local d f
  for d in "$APPS_DIR" /usr/local/share/applications /usr/share/applications "$AUTOSTART_DIR" /etc/xdg/autostart; do
    [[ -d $d ]] || continue
    for f in "$d"/*.desktop; do
      [[ -f $f ]] || continue
      grep -qE '^(Try)?Exec=.*input-leap([[:space:]]|$|")' "$f" 2>/dev/null && printf '%s\n' "$f"
    done
  done
}

qt_version_of_system() {
  local v=""
  [[ $1 == 6 ]] && v=$(ls /usr/lib*/libQt6Core.so.6.* /usr/lib/*/libQt6Core.so.6.* 2>/dev/null | head -n1)
  [[ $1 == 5 ]] && v=$(ls /usr/lib*/libQt5Core.so.5.* /usr/lib/*/libQt5Core.so.5.* 2>/dev/null | head -n1)
  [[ -n $v ]] && sed 's/.*\.so\.//' <<<"$v"
}
